export const SIDO_LIST = REGIONS.map((r) => r.sido);

export function gugunsOf(sido: string): string[] {
  return REGIONS.find((r) => r.sido === sido)?.guguns ?? [];
}

/** "서울특별시 강남구" → { sido: "서울특별시", gugun: "강남구" } */
export function splitRegion(region: string | null | undefined): { sido: string; gugun: string } {
  if (!region) return { sido: '', gugun: '' };
  const idx = region.indexOf(' ');
  if (idx === -1) return { sido: region, gugun: '' };
  return { sido: region.slice(0, idx), gugun: region.slice(idx + 1) };
}

export function joinRegion(sido: string, gugun: string): string {
  return gugun ? `${sido} ${gugun}` : sido;
}

